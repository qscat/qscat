@pytest.mark.parametrize("df, conf, expected", ALGLIB_CONFIDENCE_CASES)
def test_inv_student_t_matches_alglib_at_confidence_levels(df, conf, expected):
    assert inv_student_t(df, qscat_p(conf)) == pytest.approx(expected, rel=1e-10)


@pytest.mark.parametrize("df, p, expected", ALGLIB_PROBABILITY_CASES)
def test_inv_student_t_matches_alglib_at_probabilities(df, p, expected):
    assert inv_student_t(df, p) == pytest.approx(expected, rel=1e-10, abs=1e-12)


@pytest.mark.parametrize(
    "df, p",
    [
        (0, 0.975),
        (-1, 0.975),
        (2.5, 0.975),
        (5, 0.0),
        (5, 1.0),
        (5, 1.5),
        (5, -0.1),
    ],
)
def test_inv_student_t_rejects_inputs_alglib_rejects(df, p):
    with pytest.raises(ValueError):
        inv_student_t(df, p)


@pytest.mark.parametrize("df", [1, 2, 7, 50])
@pytest.mark.parametrize("p", [0.6, 0.9, 0.975, 0.9985])
def test_student_t_cdf_roundtrip(df, p):
    assert student_t_cdf(inv_student_t(df, p), df) == pytest.approx(p, rel=1e-12)
